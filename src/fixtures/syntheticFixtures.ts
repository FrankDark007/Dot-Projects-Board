function minutesAgo(mins: number, baseIso = REFERENCE_NOW_ISO): string {
  return new Date(Date.parse(baseIso) - mins * 60 * 1000).toISOString();
}

function secondsAgo(secs: number, baseIso = REFERENCE_NOW_ISO): string {
  return new Date(Date.parse(baseIso) - secs * 1000).toISOString();
}

function hoursAgo(hours: number, baseIso = REFERENCE_NOW_ISO): string {
  return new Date(Date.parse(baseIso) - hours * 3600 * 1000).toISOString();
}

